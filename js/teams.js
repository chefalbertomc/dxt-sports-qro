// Full taxonomy breadcrumb lookup with official team/league logos (Exact & Prefix-Stripped Team ID Matching)
function getFullTaxonomy(teamId) {
  if (!teamId || teamId === 'all') {
    return {
      sport: "Deportes",
      icon: "🏆",
      league: "Oficial",
      leagueLogo: "assets/dxt_logo.png",
      team: "DXT Sports QRO",
      teamLogo: "assets/dxt_logo.png"
    };
  }

  const cleanId = teamId.toLowerCase().trim();
  const strippedClean = cleanId.replace(/^(soc|nfl|nba|mlb|f1|ms|cat)-/, '');

  for (const s of SPORTS_CATALOG) {
    for (const l of s.leagues) {
      const team = l.teams.find(t => {
        const tid = t.id.toLowerCase();
        if (tid === cleanId) return true;
        const strippedTid = tid.replace(/^(soc|nfl|nba|mlb|f1|ms|cat)-/, '');
        return strippedTid === strippedClean;
      });
      if (team) {
        return {
          sport: s.sport,
          icon: s.icon,
          league: l.league,
          leagueLogo: l.leagueLogo || s.leagueLogo,
          team: team.name,
          teamLogo: team.logo || "assets/dxt_logo.png"
        };
      }
    }
  }
  return {
    sport: "Deportes",
    icon: "🏆",
    league: "Oficial",
    leagueLogo: "assets/dxt_logo.png",
    team: teamId.toUpperCase(),
    teamLogo: "assets/dxt_logo.png"
  };
}

function getTeamName(teamId) {
  return getFullTaxonomy(teamId).team;
}

function getLeagueByTeam(teamId) {
  const tax = getFullTaxonomy(teamId);
  return `${tax.sport} — ${tax.league}`;
}

